import AppKit
import Combine

/// 低功耗剪贴板监听：轮询 changeCount + 敏感类型过滤 + 来源白名单 + SHA-256 去重。
final class ClipboardMonitor {
    /// (原文, 来源应用名)
    var onNewText: ((String, String) -> Void)?

    var captureScope: CaptureScope = .grokOnly
    var isListening: Bool = true

    static let ownBundleIdentifier = "local.grokclip.space"
    static let pollInterval: TimeInterval = 0.4

    /// 密码管理器 / 临时剪贴板约定的敏感类型：一律跳过。
    static let sensitiveTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
    ]

    /// 浏览器关键字（同时匹配 Bundle ID 与应用名，统一小写）
    static let browserKeywords: [String] = [
        "com.apple.safari", "safari",
        "com.google.chrome", "google chrome",
        "company.thebrowser.browser", "arc",
        "com.microsoft.edgemac", "microsoft edge",
        "com.brave.browser", "brave",
        "org.mozilla.firefox", "firefox",
        "com.operasoftware.opera", "opera",
        "com.vivaldi.vivaldi", "vivaldi",
        "com.kagi.kagimacos", "orion",
        "company.thebrowser.dia", "dia",
        "ai.perplexity.comet", "comet",
    ]

    private var timer: Timer?
    private var lastChangeCount: Int
    private(set) var lastCapturedHash: String = ""

    init() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    deinit { timer?.invalidate() }

    // MARK: Lifecycle

    func start() {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 更新哈希基准（例如用户删除条目后允许再次收录同一内容）
    func resetDedup() { lastCapturedHash = "" }

    // MARK: Polling

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard isListening else { return }
        guard !Self.containsSensitiveData(pb) else { return }
        guard let app = NSWorkspace.shared.frontmostApplication,
              Self.isAllowed(app: app, scope: captureScope) else { return }
        guard let text = Self.readText(from: pb) else { return }

        let hash = ClipItem.sha256(text)
        guard hash != lastCapturedHash else { return }
        lastCapturedHash = hash
        onNewText?(text, Self.displayName(for: app))
    }

    // MARK: Filters

    static func containsSensitiveData(_ pb: NSPasteboard) -> Bool {
        guard let types = pb.types else { return false }
        return types.contains { sensitiveTypes.contains($0) }
    }

    static func isGrok(bundleID: String, name: String) -> Bool {
        if bundleID == "com.anysphere.sand" || bundleID.hasPrefix("com.anysphere.sand.") { return true }
        return name.contains("grok bot") || name == "grok"
    }

    static func isBrowser(bundleID: String, name: String) -> Bool {
        for keyword in browserKeywords {
            if keyword.contains(".") {
                if bundleID == keyword || bundleID.hasPrefix(keyword + ".") || bundleID.hasPrefix(keyword) { return true }
            } else if name == keyword || name.hasPrefix(keyword + " ") {
                return true
            }
        }
        return false
    }

    static func isAllowed(app: NSRunningApplication, scope: CaptureScope) -> Bool {
        let bundleID = (app.bundleIdentifier ?? "").lowercased()
        let name = (app.localizedName ?? "").lowercased()
        if bundleID == ownBundleIdentifier { return false }
        switch scope {
        case .grokOnly:
            return isGrok(bundleID: bundleID, name: name)
        case .grokAndBrowsers:
            return isGrok(bundleID: bundleID, name: name) || isBrowser(bundleID: bundleID, name: name)
        case .allApps:
            return true
        }
    }

    static func displayName(for app: NSRunningApplication?) -> String {
        guard let app = app else { return "未知来源" }
        return app.localizedName ?? app.bundleIdentifier ?? "未知来源"
    }

    /// 读取纯文本（保留原样字符，不做任何修剪）；空白内容视为无效。
    static func readText(from pb: NSPasteboard) -> String? {
        guard let text = pb.string(forType: .string) else { return nil }
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return nil }
        return text
    }

    static func readFileURLs(from pb: NSPasteboard) -> [URL] {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        let objects = pb.readObjects(forClasses: [NSURL.self], options: options) ?? []
        return objects.compactMap { ($0 as? URL) ?? (($0 as? NSURL).map { $0 as URL }) }
    }

    // MARK: Manual capture

    enum ManualCapture {
        case text(String, source: String)
        case files([URL], source: String)
        case sensitive
        case empty
    }

    /// 无视收录范围，直接抓取当前剪贴板（仍然跳过密码等敏感内容）。
    func captureCurrentPasteboardManually() -> ManualCapture {
        let pb = NSPasteboard.general
        lastChangeCount = pb.changeCount
        if Self.containsSensitiveData(pb) { return .sensitive }
        let source = "手动收录"
        let files = Self.readFileURLs(from: pb)
        if !files.isEmpty { return .files(files, source: source) }
        if let text = Self.readText(from: pb) {
            lastCapturedHash = ClipItem.sha256(text)
            return .text(text, source: source)
        }
        return .empty
    }

    // MARK: Silent writes (never self-trigger)

    func writeSilentlyToPasteboard(text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
        lastCapturedHash = ClipItem.sha256(text)
    }

    func writeSilentlyToPasteboard(fileURLs: [URL]) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects(fileURLs.map { $0 as NSURL })
        lastChangeCount = pb.changeCount
    }
}
